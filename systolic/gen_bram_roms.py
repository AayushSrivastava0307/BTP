#!/usr/bin/env python3
"""
gen_bram_roms.py -- writes lenet_roms_bram.v, the synthesis copy of lenet_roms.v.

lenet_roms.v stores each ROM as one huge packed-array constant indexed by the address.
Vivado builds that as a LUT multiplexer instead of block RAM (the first Vivado run used
only 19 block RAMs and 40,872 LUTs).  This script rewrites every ROM module in the standard
inferable form

    (* rom_style = "block" *) reg [W-1:0] rom [0:N-1];   initial rom[a] = ...;
    always @(`CLK_RST_EDGE) if (`RST) qa <= 0; else if (!cena) qa <= rom[aa];

with the same module name, ports, reset and read timing.  ROMs with at least 256 words go
to block RAM; smaller ones stay in LUTs (`rom_style = "distributed"`), where a 25-word ROM
is cheaper than a block RAM.

The word at each address is cut from the packed constant exactly as SystemVerilog lays it
out (element 0 at the MSB end); the script re-concatenates the words and checks they give
back the original constant bit for bit.  lenet_roms.v stays the source of truth: re-run this
after regenerating it.

    python gen_bram_roms.py
"""
import re

BLOCK_MIN_DEPTH = 256

g = open('global.v', newline='').read()
defs = {m.group(1): m.group(2).split('//')[0].strip()
        for m in re.finditer(r'`define\s+(\w+)\s+([^\r\n]*)', g)}

def ev(expr):
    for _ in range(8):
        expr = re.sub(r'`(\w+)', lambda m: '(' + defs[m.group(1)] + ')', expr)
    return eval(expr)

src = open('lenet_roms.v', newline='').read()
out = ['`include "global.v"',
       '// lenet_roms_bram.v -- GENERATED by gen_bram_roms.py from lenet_roms.v. Do not edit by hand.',
       '// Same modules, ports, contents and timing as lenet_roms.v, written so Vivado infers ROMs.',
       '']
summary = []
for m in re.finditer(r'module\s+(\w+)\s*\((.*?)\);(.*?)endmodule', src, re.S):
    name, ports, body = m.groups()
    body_nc = re.sub(r'//[^\n]*', '', body)
    d = re.search(r'logic\s*((?:\[[^\]]*\]\s*)+)\s*weight\s*=\s*\{(.*?)\};', body_nc, re.S)
    dims = [tuple(ev(x) for x in r.split(':')) for r in re.findall(r'\[([^\]]*)\]', d.group(1))]
    sizes = [abs(a - b) + 1 for a, b in dims]
    N = sizes[0]
    E = 1
    for s in sizes[1:]:
        E *= s
    D = N * E
    val = 0
    L = 0
    for sign, w, v in re.findall(r"(-?)\s*(\d+)'d(\d+)", d.group(2)):
        w = int(w)
        val = (val << w) | ((-int(v) if sign else int(v)) & ((1 << w) - 1))
        L += w
    assert L <= D, (name, L, D)
    words = [(val >> (D - (a + 1) * E)) & ((1 << E) - 1) for a in range(N)]
    chk = 0
    for wv in words:
        chk = (chk << E) | wv
    assert chk == val, name                      # words re-form the original constant exactly
    aw = re.search(r'input\s*(\[[^\]]*\])\s*aa', ports).group(1)
    qa = re.search(r'output\s+reg\s*(\[[^\]]*\])\s*qa', ports).group(1)
    style = 'block' if N >= BLOCK_MIN_DEPTH else 'distributed'
    out.append('module %s(' % name)
    out.append('\tinput\t\t\tclk,')
    out.append('\tinput\t\t\trstn,')
    out.append('\tinput\t%s\taa,' % aw)
    out.append('\tinput\t\t\tcena,')
    out.append('\toutput reg\t%s\tqa' % qa)
    out.append('\t);')
    out.append('\t(* rom_style = "%s" *) reg [%d:0] rom [0:%d];' % (style, E - 1, N - 1))
    out.append('\tinitial begin')
    for a, wv in enumerate(words):
        out.append("\t\trom[%d] = %d'h%0*x;" % (a, E, (E + 3) // 4, wv))
    out.append('\tend')
    out.append('\talways @(`CLK_RST_EDGE)')
    out.append('\t\tif (`RST)\t\tqa <= 0;')
    out.append('\t\telse if (!cena)\tqa <= rom[aa];')
    out.append('endmodule')
    out.append('')
    summary.append('%-18s %5d x %5d bits  -> %s' % (name, N, E, style))
open('lenet_roms_bram.v', 'w', newline='\n').write('\n'.join(out))
print('\n'.join(summary))
