#!/usr/bin/env python3
"""
gen_fc2_par_rom.py -- builds fc2_par_rom.v for the parallel fc2 engine (fc2_par.v).

The baseline weight ROM (wieght_fc2_rom in lenet_roms.v) holds one 16-bit weight per
address, at address  b*120 + k  (b = output neuron 0..83, k = input 0..119).

The parallel engine computes P neurons at once, so it needs P weights per read.
This script repacks the same 10,080 weights into 84/P groups x 120 words of P*16 bits:

    word[g*120 + k] bits [16*j +: 16] = w[(g*P + j)*120 + k]     j = 0..P-1

and the 84 biases into 84/P words of P*24 bits:

    bias_word[g] bits [24*j +: 24] = bias[g*P + j]

No value is changed, only where it is stored.  Run from the folder holding lenet_roms.v:

    python gen_fc2_par_rom.py            (P = 12, writes fc2_par_rom.v)
"""
import re, sys

P = int(sys.argv[1]) if len(sys.argv) > 1 else 12
NIN, NOUT = 120, 84
assert NOUT % P == 0, "P must divide 84"
G = NOUT // P

src = open("lenet_roms.v").read()

def values(module):
    m = re.search(r"module\s+%s\b(.*?)endmodule" % module, src, re.S)
    body = m.group(1)
    init = body[body.index("= {") + 3: body.index("};")]
    return [(-1 if s else 1) * int(v) for s, v in re.findall(r"(-?)\s*\d+'d(\d+)", init)]

w = values("wieght_fc2_rom")
b = values("bias_fc2_rom")
assert len(w) == NIN * NOUT, len(w)
assert len(b) == NOUT, len(b)

def word(vals, bits):
    out = 0
    for j, v in enumerate(vals):
        out |= (v & ((1 << bits) - 1)) << (bits * j)
    return out

WW, BW = 16 * P, 24 * P
AW = (G * NIN - 1).bit_length()
GW = max(1, (G - 1).bit_length())

lines = []
lines.append("// fc2_par_rom.v -- GENERATED by gen_fc2_par_rom.py from lenet_roms.v. Do not edit by hand.")
lines.append("// Same fc2 weights and biases as wieght_fc2_rom / bias_fc2_rom, repacked %d per word." % P)
lines.append("")
lines.append("module fc2_par_weight_rom (")
lines.append("\tinput\t\t\t\tclk,")
lines.append("\tinput\t\t\t\tcena,\t\t// active low, as in the other ROMs")
lines.append("\tinput\t\t[%d:0]\taa,\t\t\t// g*%d + k" % (AW - 1, NIN))
lines.append("\toutput reg\t[%d:0]\tqa\t\t\t// [16*j +: 16] = weight of neuron g*%d+j, input k" % (WW - 1, P))
lines.append("\t);")
lines.append("\treg [%d:0] rom [0:%d];" % (WW - 1, G * NIN - 1))
lines.append("\tinitial begin")
for g in range(G):
    for k in range(NIN):
        vals = [w[(g * P + j) * NIN + k] for j in range(P)]
        lines.append("\t\trom[%d] = %d'h%0*x;" % (g * NIN + k, WW, WW // 4, word(vals, 16)))
lines.append("\tend")
lines.append("\talways @(posedge clk) if (!cena) qa <= rom[aa];")
lines.append("endmodule")
lines.append("")
lines.append("module fc2_par_bias_rom (")
lines.append("\tinput\t\t\t\tclk,")
lines.append("\tinput\t\t\t\tcena,")
lines.append("\tinput\t\t[%d:0]\taa,\t\t\t// group g" % (GW - 1))
lines.append("\toutput reg\t[%d:0]\tqa\t\t\t// [24*j +: 24] = bias of neuron g*%d+j" % (BW - 1, P))
lines.append("\t);")
lines.append("\treg [%d:0] rom [0:%d];" % (BW - 1, G - 1))
lines.append("\tinitial begin")
for g in range(G):
    lines.append("\t\trom[%d] = %d'h%0*x;" % (g, BW, BW // 4, word(b[g * P:(g + 1) * P], 24)))
lines.append("\tend")
lines.append("\talways @(posedge clk) if (!cena) qa <= rom[aa];")
lines.append("endmodule")

open("fc2_par_rom.v", "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote fc2_par_rom.v: P=%d, %d weight words x %d bits, %d bias words x %d bits" % (P, G * NIN, WW, G, BW))
