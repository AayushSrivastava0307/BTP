# gen_sim_roms.py [src_dir] [out_file] -- simulation-only copy of lenet_roms.v with the packed-array initialisers
# turned into plain memories (Verilator/Icarus choke on the originals). Every module keeps its
# ports and its read behaviour: qa <= rom[aa] on the clock, reset to 0. The word at each address
# is computed exactly as SystemVerilog lays out the packed array (element 0 at the MSB end,
# a narrower literal zero-extended on the left), and self-checked below.
import re, sys
SRC = sys.argv[1] if len(sys.argv) > 1 else '..'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'lenet_roms_sim.v'
g = open(SRC + '/global.v', newline='').read()
defs = {m.group(1): m.group(2).split('//')[0].strip() for m in re.finditer(r'`define\s+(\w+)\s+([^\r\n]*)', g)}
def ev(expr):
    for _ in range(6):
        expr = re.sub(r'`(\w+)', lambda m: '(' + defs[m.group(1)] + ')', expr)
    return eval(expr)
src = open(SRC + '/lenet_roms.v', newline='').read()
out = ['`include "global.v"', '// SIMULATION ONLY -- generated by gen_sim_roms.py from lenet_roms.v', '']
for m in re.finditer(r'module\s+(\w+)\s*\((.*?)\);(.*?)endmodule', src, re.S):
    name, ports, body = m.groups()
    body_nc = re.sub(r'//[^\n]*', '', body)
    d = re.search(r'logic\s*((?:\[[^\]]*\]\s*)+)\s*weight\s*=\s*\{(.*?)\};', body_nc, re.S)
    dims = [tuple(ev(x) for x in r.split(':')) for r in re.findall(r'\[([^\]]*)\]', d.group(1))]
    sizes = [abs(a - b) + 1 for a, b in dims]
    N = sizes[0]; E = 1
    for s in sizes[1:]: E *= s
    D = N * E
    lits = re.findall(r"(-?)\s*(\d+)'d(\d+)", d.group(2))
    val = 0; L = 0
    for sign, w, v in lits:
        w = int(w); x = (-int(v) if sign else int(v)) & ((1 << w) - 1)
        val = (val << w) | x; L += w
    assert L <= D, (name, L, D)
    words = [(val >> (D - (a + 1) * E)) & ((1 << E) - 1) for a in range(N)]
    # self-check: re-concatenate the words and compare with the original packed value
    chk = 0
    for wv in words: chk = (chk << E) | wv
    assert chk == val, name
    aw = re.search(r'input\s*(\[[^\]]*\])\s*aa', ports).group(1)
    qa = re.search(r'output\s+reg\s*(\[[^\]]*\])\s*qa', ports).group(1)
    out.append('module %s(input clk, input rstn, input %s aa, input cena, output reg %s qa);' % (name, aw, qa))
    out.append('\treg [%d:0] rom [0:%d];' % (E - 1, N - 1))
    out.append('\tinitial begin')
    for a, wv in enumerate(words):
        out.append("\t\trom[%d] = %d'h%x;" % (a, E, wv))
    out.append('\tend')
    out.append('\talways @(`CLK_RST_EDGE)\n\t\tif (`RST) qa <= 0;\n\t\telse if (!cena) qa <= rom[aa];')
    out.append('endmodule\n')
    print('%-18s %5d words x %5d bits (literals %d bits of %d)' % (name, N, E, L, D))
open(OUT, 'w').write('\n'.join(out))
