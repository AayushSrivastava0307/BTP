`include "global.v"

// fc2_par -- fc2 with P output neurons computed at once.
//
// The baseline fc2 (iterator + conv/acc/mac) walks the 84 neurons one after another and
// does one multiply per clock: 84 x 120 = 10,080 clocks.  Here P multiply-accumulate
// units share each input value, so the layer runs as 84/P groups of 120 clocks.
//
//   group g = 0 .. 84/P-1, input k = 0 .. 119
//   acc[j] = bias[g*P+j] + SUM_k x[k] * w[(g*P+j)*120 + k]      j = 0 .. P-1
//   q      = acc[30:15]                                         (same slice as acc in cnn.v)
//
// Bit-exactness: the baseline forms the same sum in the same order (bias added with the
// first product, then each product in k order) in a 32-bit register with no saturation,
// so every q is identical.  Results leave one per clock, neuron 0 first, through the same
// q / q_en interface as conv_fc2, so relu_fc2 and relu_fc2_buf are unchanged.
//
// Weights come from fc2_par_rom.v (generated by gen_fc2_par_rom.py), which holds the same
// values as wieght_fc2_rom / bias_fc2_rom repacked P per word.
//
// Timing, per group of 120 inputs:
//   c     counters k, g                     (issue)
//   c+1   aa_data / rom address registered
//   c+2   SRAM data and ROM words valid      -> product registered at c+3
//   c+3   accumulate
// After the last input of a group the P sums are copied to an output shift register and
// sent one per clock while the next group is already accumulating.

module fc2_par #(
	parameter P    = 12,		// neurons per group; must divide NOUT
	parameter NIN  = 120,		// fc2 inputs  (fc1 outputs)
	parameter NOUT = 84,		// fc2 outputs
	parameter WIGHT_SHIFT = 15
	)(
	input						clk,
	input						rstn,
	input						go,			// pulse: fc1 is done
	// read port of relu_fc1_buf
	output reg	[6:0]			aa_data,
	output reg					cena_data,	// active low
	input		[`WD:0]			qa_data,
	// results, in neuron order, same meaning as conv_fc2's q / q_en
	output reg					q_en,
	output reg	[`WD:0]			q,
	output reg					ready		// pulse: all NOUT results sent
	);

	localparam G   = NOUT / P;
	localparam AW  = $clog2(G * NIN);
	localparam GW  = (G > 1) ? $clog2(G) : 1;
	localparam KW  = $clog2(NIN);
	localparam ACC = `WDP * 2;			// 32-bit accumulator, as in acc

	// ---- issue: walk g = 0..G-1, k = 0..NIN-1 ---------------------------------
	reg				run;
	reg	[KW-1:0]	k;
	reg	[GW-1:0]	g;
	wire			k_last = (k == NIN - 1);
	wire			g_last = (g == G - 1);

	always @(`CLK_RST_EDGE)
		if (`RST)						run <= 0;
		else if (go)					run <= 1;
		else if (run & k_last & g_last)	run <= 0;

	always @(`CLK_RST_EDGE)
		if (`RST)		k <= 0;
		else if (!run)	k <= 0;
		else			k <= k_last ? 0 : k + 1;

	always @(`CLK_RST_EDGE)
		if (`RST)				g <= 0;
		else if (!run)			g <= 0;
		else if (k_last)		g <= g_last ? 0 : g + 1;

	// ---- address registers (1 clock), memories read on the next edge -----------
	reg	[AW-1:0]	aa_w;
	reg	[GW-1:0]	aa_b;
	always @(`CLK_RST_EDGE)
		if (`RST) begin
			aa_data <= 0; aa_w <= 0; aa_b <= 0; cena_data <= 1;
		end else begin
			aa_data   <= k;
			aa_w      <= g * NIN + k;
			aa_b      <= g;
			cena_data <= ~run;
		end

	wire	[16*P-1:0]	w_word;
	wire	[24*P-1:0]	b_word;
	fc2_par_weight_rom u_wrom (.clk(clk), .cena(cena_data), .aa(aa_w), .qa(w_word));
	fc2_par_bias_rom   u_brom (.clk(clk), .cena(cena_data), .aa(aa_b), .qa(b_word));

	// control flags, delayed to line up with the data
	//   [0] = issue cycle, [2] = data valid, [3] = product valid (accumulate)
	reg	[3:0]	v_d, first_d, last_d;
	always @(`CLK_RST_EDGE)
		if (`RST) begin
			v_d <= 0; first_d <= 0; last_d <= 0;
		end else begin
			v_d     <= {v_d[2:0],     run};
			first_d <= {first_d[2:0], run & (k == 0)};
			last_d  <= {last_d[2:0],  run & k_last};
		end

	// ---- P multiply-accumulate lanes --------------------------------------------
	reg	signed	[ACC-1:0]	prod [0:P-1];
	reg	signed	[ACC-1:0]	acc  [0:P-1];
	reg	signed	[23:0]		bias_d [0:P-1];

	genvar j;
	generate
		for (j = 0; j < P; j = j + 1) begin : lane
			wire signed [`WD:0]	x  = qa_data;
			wire signed [`WD:0]	wj = w_word[16*j +: 16];
			always @(`CLK_RST_EDGE)
				if (`RST) begin
					prod[j] <= 0; bias_d[j] <= 0;
				end else begin
					prod[j]   <= x * wj;				// 16 x 16 -> 32, one DSP
					bias_d[j] <= b_word[24*j +: 24];
				end
			always @(`CLK_RST_EDGE)
				if (`RST)				acc[j] <= 0;
				else if (v_d[2]) begin
					if (first_d[2])		acc[j] <= prod[j] + bias_d[j];
					else				acc[j] <= prod[j] + acc[j];
				end
		end
	endgenerate

	// ---- send the P results of a group, one per clock ---------------------------
	// last_d[2] marks the cycle that adds the final product; the sums are complete
	// one clock later, when done_grp is high.
	reg						done_grp;
	reg	[ACC-1:0]			outq [0:P-1];
	reg	[$clog2(P+1)-1:0]	n_left;
	reg	[$clog2(NOUT+1)-1:0] n_sent;
	integer i;

	always @(`CLK_RST_EDGE)
		if (`RST)	done_grp <= 0;
		else		done_grp <= v_d[2] & last_d[2];

	always @(`CLK_RST_EDGE)
		if (`RST) begin
			n_left <= 0; q_en <= 0; q <= 0;
			for (i = 0; i < P; i = i + 1) outq[i] <= 0;
		end else if (done_grp) begin
			for (i = 0; i < P; i = i + 1) outq[i] <= acc[i];
			n_left <= P;
			q_en   <= 0;
		end else if (n_left != 0) begin
			q      <= outq[0][ACC-2:WIGHT_SHIFT];	// acc[30:15], the slice acc in cnn.v keeps
			q_en   <= 1;
			for (i = 0; i < P - 1; i = i + 1) outq[i] <= outq[i + 1];
			n_left <= n_left - 1;
		end else
			q_en   <= 0;

	// ready: a few clocks after the last result, so it has been written to relu_fc2_buf
	reg	[3:0]	fin_d;
	always @(`CLK_RST_EDGE)
		if (`RST)		n_sent <= 0;
		else if (go)	n_sent <= 0;
		else if (q_en)	n_sent <= n_sent + 1;

	always @(`CLK_RST_EDGE)
		if (`RST) begin
			fin_d <= 0; ready <= 0;
		end else begin
			fin_d <= {fin_d[2:0], q_en & (n_sent == NOUT - 1)};
			ready <= fin_d[3];
		end

endmodule
